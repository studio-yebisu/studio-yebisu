"""Generate crawlable image cards and on-site video-sharing pages."""
from html import escape
from html.parser import HTMLParser
import json
from pathlib import Path
import re
from urllib.parse import urljoin, urlsplit
from social_images import prepare_image, check_images, asset_path, digest

ROOT = Path(__file__).resolve().parents[1]
ORIENTATIONS = ('landscape', 'portrait')
MARKER = '<!-- Generated by scripts/social_cards.py -->'


def public_base():
    value = json.loads((ROOT / 'data/projects.json').read_text('utf-8'))['site_url']
    url = urlsplit(value)
    if url.scheme != 'https' or not url.hostname or url.username or url.password or url.query or url.fragment or not value.endswith('/'):
        raise ValueError('Social cards require a public HTTPS site_url ending in /')
    if url.hostname in ('localhost', '::1') or url.hostname.startswith('127.'):
        raise ValueError('Loopback URLs cannot be crawled by X')
    return value


def e(value):
    return escape(str(value), quote=True)


def description(case):
    return ' '.join(str(case.get('catalog_entry', {}).get('summary') or case['summary']).split())[:190]


def write_page(target, relative, content):
    path = (target / relative).resolve()
    if not path.is_relative_to(target.resolve()):
        raise ValueError('Generated page escapes the publication directory')
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and MARKER not in path.read_text('utf-8'):
        raise ValueError(f'Preserve non-generated page: {path}')
    path.write_text(content, 'utf-8')


def render_share_page(case, orientation, asset, image, page_path, base, brand, portrait_asset=None):
    ident = case['id']
    title = case.get('catalog_entry', {}).get('name') or case['title']
    summary = description(case)
    page_url = urljoin(base, page_path)
    image_url = urljoin(base, image['path'])
    image_alt = f'{title}の紹介動画の一場面。{case["video_license"]["credit"]}'
    tags = {
        'twitter:card': 'summary_large_image', 'twitter:site': '@studio_yebisu',
        'twitter:creator': '@studio_yebisu', 'twitter:title': title + '｜紹介と作例',
        'twitter:description': summary, 'twitter:image': image_url,
        'twitter:image:alt': image_alt,
        'og:type': 'website', 'og:site_name': brand, 'og:url': page_url,
        'og:title': title + '｜紹介と作例', 'og:description': summary,
        'og:image': image_url, 'og:image:secure_url': image_url,
        'og:image:type': 'image/jpeg', 'og:image:width': str(image['width']),
        'og:image:height': str(image['height']), 'og:image:alt': image_alt,
    }
    meta = '\n'.join('  <meta ' + ('property' if key.startswith('og:') else 'name')
                     + f'="{key}" content="{e(value)}">' for key, value in tags.items())
    player_path = f'embed/{ident}-{orientation}.html'
    frame_options = download_options = script = ''
    if portrait_asset:
        frame_options = (f' data-responsive-player data-landscape="../embed/{ident}-landscape.html"'
                         f' data-portrait="../embed/{ident}-portrait.html"'
                         f' data-landscape-width="{asset["width"]}" data-landscape-height="{asset["height"]}"'
                         f' data-portrait-width="{portrait_asset["width"]}" data-portrait-height="{portrait_asset["height"]}"')
        download_options = (f' data-responsive-download data-landscape="../{e(case["video_download_landscape"])}"'
                            f' data-portrait="../{e(case["video_download_portrait"])}"')
        script = '  <script src="../share-page.js"></script>\n'
    return f'''<!doctype html>
{MARKER}
<html lang="ja">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
  <title>{e(title)}｜紹介動画｜{e(brand)}</title>
  <meta name="description" content="{e(summary)}">
  <link rel="canonical" href="{e(page_url)}">
{meta}
  <link rel="stylesheet" href="../share.css">
</head>
<body class="image-share-page">
  <main id="main" class="image-share-stage" aria-label="{e(title)}の紹介動画">
    <iframe class="image-share-frame is-{orientation}" src="../{player_path}"{frame_options} title="{e(title)}の紹介動画" width="{asset['width']}" height="{asset['height']}" allow="autoplay; fullscreen; picture-in-picture" allowfullscreen></iframe>
  </main>
  <details class="image-share-menu">
    <summary aria-label="動画の操作メニュー" title="動画の操作メニュー">⋯</summary>
    <nav aria-label="動画の操作">
      <a href="../case.html?id={ident}">詳しい紹介を読む</a>
      <a href="../{e(asset['path'])}"{download_options} download>動画を保存（引用元入り）</a>
      <a href="{ident}-landscape.html">横向きで見る</a>
      <a href="{ident}-portrait.html">縦向きで見る</a>
      <a href="../media-rights.html">利用条件・クレジット</a>
    </nav>
  </details>
{script}</body>
</html>
'''


def build_social_pages(target, cases):
    target = Path(target)
    base = public_base()
    brand = json.loads((ROOT / 'data/projects.json').read_text('utf-8'))['title']
    downloads = json.loads((target / 'data/video-downloads.json').read_text('utf-8'))
    media = {(a['case_id'], a['orientation']): a for a in downloads['assets']}
    old_manifest = target / 'data/social-cards.json'
    previous = json.loads(old_manifest.read_text('utf-8')) if old_manifest.exists() else {}
    previous_images = {i['case_id']: i for i in previous.get('images', [])}
    cards, image_cards, images = [], [], []
    for case in cases:
        ident = case['id']
        if not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', ident):
            raise ValueError(f'Unsafe social-card id: {ident}')
        title = case.get('catalog_entry', {}).get('name') or case['title']
        image = prepare_image(target, ident, media[ident, 'landscape'], previous_images.get(ident))
        images.append(image)
        image_page = f'share/{ident}-card.html'
        write_page(target, image_page, render_share_page(case, 'landscape', media[ident, 'landscape'],
                                                        image, image_page, base, brand, portrait_asset=media[ident, 'portrait']))
        image_cards.append({'case_id': ident, 'page': image_page, 'url': urljoin(base, image_page),
                            'image': image['path']})
        for orientation in ORIENTATIONS:
            asset = media[ident, orientation]
            stream = case['video_download_' + orientation]
            if stream != asset['path']:
                raise ValueError(f'Uncredited social-card stream: {ident}')
            poster = case['poster_' + orientation]
            for relative in (stream, poster):
                path = (target / relative).resolve()
                if not path.is_relative_to(target.resolve()) or not path.is_file():
                    raise ValueError(f'Missing local card asset: {relative}')
            width, height = asset['width'], asset['height']
            filename = f'{ident}-{orientation}.html'
            page_path, player_path = 'share/' + filename, 'embed/' + filename
            page_url, player_url = urljoin(base, page_path), urljoin(base, player_path)
            stream_url = urljoin(base, stream)
            share_html = render_share_page(case, orientation, asset, image, page_path, base, brand)
            player_html = f'''<!doctype html>
{MARKER}
<html lang="ja">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{e(title)}｜動画プレーヤー</title>
  <link rel="stylesheet" href="../embed-player.css">
</head>
<body>
  <main class="embed-shell" aria-label="{e(title)}の紹介動画">
    <video src="../{e(stream)}" poster="../{e(poster)}" width="{width}" height="{height}" muted loop playsinline controls preload="metadata" controlslist="nodownload" aria-label="{e(title)}の紹介動画"></video>
    <button class="embed-play" type="button" hidden>動画を再生</button>
    <p class="embed-error" role="status" hidden>動画を読み込めませんでした。<a href="../{e(stream)}" target="_blank" rel="noopener">動画を開く</a></p>
  </main>
  <script src="../embed-player.js"></script>
</body>
</html>
'''
            write_page(target, page_path, share_html)
            write_page(target, player_path, player_html)
            cards.append({'case_id': ident, 'orientation': orientation, 'page': page_path,
                          'url': page_url, 'player': player_path, 'player_url': player_url,
                          'stream': stream, 'stream_url': stream_url, 'poster': poster,
                          'image': image['path'], 'width': width, 'height': height})
    owned = {card[key] for card in cards + image_cards for key in ('page', 'player') if key in card}
    for card in previous.get('cards', []) + previous.get('image_cards', []):
        for key in ('page', 'player'):
            if key not in card:
                continue
            relative = card[key]
            path = (target / relative).resolve()
            if relative not in owned and path.is_file():
                if not path.is_relative_to(target.resolve()) or MARKER not in path.read_text('utf-8'):
                    raise ValueError(f'Preserve unexpected stale page: {path}')
                path.unlink()
    owned_images = {image['path'] for image in images}
    for image in previous.get('images', []):
        if image['path'] in owned_images:
            continue
        path = asset_path(target, image['path'])
        if path.is_file():
            if not path.is_relative_to((target / 'media/social-cards').resolve()) or digest(path) != image['sha256']:
                raise ValueError(f'Preserve unexpected stale sharing image: {path}')
            path.unlink()
    manifest = {'schema_version': 2, 'base_url': base, 'card_type': 'summary_large_image', 'page_layout': 'diagram-only',
                'validation_scope': 'Prepared static image cards and local playback; X display requires publicly reachable HTTPS pages/images and separate verification after publication.',
                'x_card_display_verified': False, 'images': images, 'image_cards': image_cards, 'cards': cards}
    old_manifest.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', 'utf-8')
    return len(cards) + len(image_cards)


class CardHead(HTMLParser):
    def __init__(self):
        super().__init__()
        self.meta = {}
        self.in_head = False
        self.videos = []
        self.frames = []
        self.canonicals = []

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == 'video':
            self.videos.append(attrs)
        if tag == 'iframe':
            self.frames.append(attrs)
        if tag == 'head':
            self.in_head = True
        if tag == 'link' and self.in_head and attrs.get('rel') == 'canonical':
            self.canonicals.append(attrs.get('href'))
        if tag == 'meta' and self.in_head:
            key = attrs.get('name') or attrs.get('property')
            if key:
                assert key not in self.meta, f'Duplicate card metadata: {key}'
                self.meta[key] = attrs.get('content')

    def handle_endtag(self, tag):
        if tag == 'head':
            self.in_head = False


def check_social_pages(target, cases):
    target = Path(target)
    manifest = json.loads((target / 'data/social-cards.json').read_text('utf-8'))
    cards = manifest['cards']
    expected = {(case['id'], o) for case in cases for o in ORIENTATIONS}
    assert len(cards) == len(expected) and {(c['case_id'], c['orientation']) for c in cards} == expected, 'Missing or duplicate orientation pages'
    cases_by_id = {c['id']: c for c in cases}
    base = public_base()
    image_cards = manifest['image_cards']
    assert len(image_cards) == len(cases) and {c['case_id'] for c in image_cards} == set(cases_by_id), 'Missing or duplicate primary image cards'
    check_images(target, manifest['images'], cases)
    images = {i['case_id']: i for i in manifest['images']}

    def check_metadata(card):
        parser = CardHead()
        parser.feed((target / card['page']).read_text('utf-8'))
        tags = parser.meta
        assert tags['twitter:card'] == 'summary_large_image'
        assert not any(k.startswith(('twitter:player', 'og:video')) for k in tags), 'Image card still advertises a video player'
        assert tags['twitter:site'] == tags['twitter:creator'] == '@studio_yebisu'
        assert tags['twitter:image'] == tags['og:image'] == tags['og:image:secure_url'] == urljoin(base, images[card['case_id']]['path'])
        assert tags['twitter:image:alt'] == tags['og:image:alt'] and tags['twitter:image:alt']
        assert tags['og:image:type'] == 'image/jpeg'
        assert (tags['og:image:width'], tags['og:image:height']) == ('1200', '600')
        assert tags['og:type'] == 'website'
        assert tags['og:url'] == card['url'] == urljoin(base, card['page'])
        assert parser.canonicals == [card['url']]
        for key in ('twitter:image', 'og:url', 'og:image'):
            assert tags[key].startswith(base), f'Card uses an unpublished or foreign asset: {key}'
        return parser

    for card in cards:
        parser = check_metadata(card)
        assert card['stream'] == cases_by_id[card['case_id']]['video_download_' + card['orientation']], 'Sharing page bypasses the credited video'
        assert len(parser.frames) == 1 and parser.frames[0]['src'] == '../' + card['player'], 'Shared page embeds another player'
        player = CardHead()
        player.feed((target / card['player']).read_text('utf-8'))
        assert len(player.videos) == 1 and player.videos[0]['src'] == '../' + card['stream'], 'Embedded player bypasses the credited stream'
        assert all(key in player.videos[0] for key in ('muted', 'playsinline', 'controls')), 'Player lost inline/muted playback or its manual controls'
        for key in ('player', 'stream', 'poster'):
            assert (target / card[key]).resolve().is_relative_to(target.resolve()) and (target / card[key]).is_file()
    for card in image_cards:
        parser = check_metadata(card)
        assert len(parser.frames) == 1 and 'data-responsive-player' in parser.frames[0], 'Primary sharing page lost its responsive video'
        frame = parser.frames[0]
        assert frame['src'] == frame['data-landscape'] == f'../embed/{card["case_id"]}-landscape.html'
        assert frame['data-portrait'] == f'../embed/{card["case_id"]}-portrait.html'
    return {'social_image_cards': len(image_cards), 'social_orientation_pages': len(cards),
            'social_embed_players': len(cards), 'x_card_display_verified': False}
